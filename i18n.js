const defaultLanguage = "sr";
const supportedLanguages = ["sr", "en"];
const textAttributes = ["aria-label", "alt", "placeholder", "title"];
const originalTitle = document.title;

const normalizeText = (value) => value.replace(/\s+/g, " ").trim();

const getLanguage = () => {
  const params = new URLSearchParams(window.location.search);
  const queryLanguage = params.get("lang");
  const savedLanguage = window.localStorage.getItem("localPassLanguage");
  return supportedLanguages.includes(queryLanguage)
    ? queryLanguage
    : supportedLanguages.includes(savedLanguage)
      ? savedLanguage
      : defaultLanguage;
};

const translateValue = (value, language) => {
  if (language === "en") {
    return value;
  }

  const normalized = normalizeText(value);
  return translations[language]?.[normalized] || value;
};

const translateTextNode = (node, language) => {
  if (!node.datasetKey) {
    node.datasetKey = normalizeText(node.nodeValue);
  }

  const key = node.datasetKey;
  if (!key) {
    return;
  }

  const translated = language === "en" ? key : translations[language]?.[key];
  if (!translated) {
    return;
  }

  const leading = node.nodeValue.match(/^\s*/)?.[0] || "";
  const trailing = node.nodeValue.match(/\s*$/)?.[0] || "";
  node.nodeValue = `${leading}${translated}${trailing}`;
};

const translateAttributes = (element, language) => {
  textAttributes.forEach((attribute) => {
    if (!element.hasAttribute(attribute)) {
      return;
    }

    const storageAttribute = `data-i18n-${attribute}`;
    if (!element.hasAttribute(storageAttribute)) {
      element.setAttribute(storageAttribute, normalizeText(element.getAttribute(attribute)));
    }

    const key = element.getAttribute(storageAttribute);
    const translated = language === "en" ? key : translations[language]?.[key];
    if (translated) {
      element.setAttribute(attribute, translated);
    }
  });
};

const applyLanguage = (language) => {
  document.documentElement.lang = language;
  document.title = language === "en" ? originalTitle : translateValue(originalTitle, language);

  document.querySelectorAll("*").forEach((element) => translateAttributes(element, language));

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    translateTextNode(node, language);
    node = walker.nextNode();
  }

  document.querySelectorAll("[data-lang-option]").forEach((button) => {
    const active = button.dataset.langOption === language;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
};

const setLanguage = (language) => {
  if (!supportedLanguages.includes(language)) {
    return;
  }

  window.localStorage.setItem("localPassLanguage", language);
  applyLanguage(language);
};

const injectLanguageSwitch = () => {
  const header = document.querySelector(".site-header");
  const cta = header?.querySelector(".header-cta");
  if (!header || header.querySelector(".language-switch")) {
    return;
  }

  const headerActions = document.createElement("div");
  headerActions.className = "header-actions";

  const switcher = document.createElement("div");
  switcher.className = "language-switch";
  switcher.setAttribute("aria-label", "Language");
  switcher.innerHTML = `
    <button type="button" data-lang-option="sr">SR</button>
    <button type="button" data-lang-option="en">EN</button>
  `;

  switcher.addEventListener("click", (event) => {
    const button = event.target.closest("[data-lang-option]");
    if (button) {
      setLanguage(button.dataset.langOption);
    }
  });

  header.insertBefore(headerActions, cta);
  headerActions.append(switcher);
  if (cta) {
    headerActions.append(cta);
  }
};

const setupSmallTabletMenu = () => {
  const toggle = document.querySelector(".menu-toggle");
  const menu = document.querySelector(".small-tablet-menu");
  if (!toggle || !menu || toggle.dataset.menuReady === "true") {
    return;
  }
  toggle.dataset.menuReady = "true";

  const setOpen = (isOpen) => {
    const labelKey = isOpen ? "Close menu" : "Open menu";
    document.body.classList.toggle("menu-open", isOpen);
    toggle.setAttribute("aria-expanded", String(isOpen));
    toggle.setAttribute("data-i18n-aria-label", labelKey);
    toggle.setAttribute("aria-label", translateValue(labelKey, getLanguage()));
    menu.setAttribute("aria-hidden", String(!isOpen));
  };

  toggle.addEventListener("click", () => {
    setOpen(!document.body.classList.contains("menu-open"));
  });

  menu.addEventListener("click", (event) => {
    if (event.target.closest("a")) {
      setOpen(false);
    }
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      setOpen(false);
    }
  });
};

const bootInterface = () => {
  injectLanguageSwitch();
  setupSmallTabletMenu();
  applyLanguage(getLanguage());
};

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", bootInterface);
} else {
  bootInterface();
}
